'use strict';

const fs = require('node:fs');
const path = require('node:path');

const dashboardRoot = path.resolve(__dirname, '..');
const envPath = path.join(dashboardRoot, '.env');
const outputPath = path.join(dashboardRoot, 'public', 'js', 'runtime-config.js');

function parseEnvFile(contents) {
  return String(contents || '')
    .split(/\r?\n/)
    .reduce(function (values, line) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) return values;

      const separatorIndex = trimmed.indexOf('=');
      if (separatorIndex < 1) return values;

      const name = trimmed.slice(0, separatorIndex).trim();
      let value = trimmed.slice(separatorIndex + 1).trim();
      if (
        value.length >= 2 &&
        ((value.startsWith('"') && value.endsWith('"')) ||
          (value.startsWith("'") && value.endsWith("'")))
      ) {
        value = value.slice(1, -1);
      }
      values[name] = value;
      return values;
    }, {});
}

const fileEnvironment = fs.existsSync(envPath)
  ? parseEnvFile(fs.readFileSync(envPath, 'utf8'))
  : {};
const hereApiKey = String(process.env.HERE_API_KEY || fileEnvironment.HERE_API_KEY || '').trim();

const generatedSource = [
  '// Generated by scripts/generate-runtime-config.js. Do not commit this file.',
  'window.FaceRollConfig = Object.freeze({',
  '  HERE_API_KEY: ' + JSON.stringify(hereApiKey),
  '});',
  '',
].join('\n');

fs.writeFileSync(outputPath, generatedSource, { encoding: 'utf8', mode: 0o600 });

if (hereApiKey) {
  console.log('Generated public/js/runtime-config.js with HERE_API_KEY.');
} else {
  console.warn(
    'Generated runtime config without a HERE_API_KEY. The Course Settings page will show a configuration message.'
  );
}
